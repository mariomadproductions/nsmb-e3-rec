// These templates must be force inlined with NTR_INLINE
// to avoid generating extra out-of-line template instantiations and function calls.
//
// Example: With force inline (NTR_INLINE), the compiler directly emits the logic for each use site,
// resulting in smaller and faster code, especially for small accessor templates.
//
// Example assembly with force inline:
//   - No calls to getValue<T>; logic is inlined into the caller.
//   - Only calls to findData remain.
//   - No stack usage for std::optional temporaries.
//
// Example assembly without force inline:
//   - getValue<T> is emitted as a separate function.
//   - Each use site calls getValue<T>, passing arguments on the stack.
//   - Extra stack usage and code size from std::optional temporaries and function call overhead.
//
// For embedded/console targets, forced inlining is critical for performance and code size.

// Flags are stored separately from data entries, allowing us to use 1+N u32s (1 for count, N for hash) instead of 2N u32s (hash and empty offset together).

// The accessors below reinterpret bytes out of the level block, so what they
// require of T is that copying it that way is meaningful -- not that it is a
// number. `level-data:` can name any type, and a struct is as valid an entry
// as a u32.

template<class T>
struct SizedArray {
	u32 size = 0;
	T* values = nullptr;
};

